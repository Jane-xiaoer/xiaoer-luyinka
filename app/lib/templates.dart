/// 词库（模板/常用词.md）里的一个词：正确写法 + 常被听成什么。
class VocabEntry {
  final String word;
  final List<String> wrong;
  const VocabEntry(this.word, [this.wrong = const []]);
}

final _vocabLine = RegExp(r'^[-*]\s*(.+?)\s*(?:[（(]\s*(?:不是|常被听成|常听成|听成|错成|常被转错成)[:：]?\s*(.*?)\s*[）)])?\s*$');

/// 读词库：「- 词」「- 词（常被听成 A、B）」「- 王总（不是 王宗）」都认。返回（词表, 其他看不懂的正文行，原样留着）。
(List<VocabEntry>, List<String>) parseVocab(String raw) {
  final out = <VocabEntry>[];
  final extra = <String>[];
  for (final l in raw.replaceAll(RegExp(r'<!--[\s\S]*?-->'), '').split('\n')) {
    final t = l.trim();
    if (t.isEmpty || t.startsWith('>') || RegExp(r'^#\s').hasMatch(t)) continue;
    final m = _vocabLine.firstMatch(t);
    if (m == null) {
      extra.add(l);
      continue;
    }
    final wrong = (m[2] ?? '').split(RegExp(r'[、,，/／;；\s]+')).map((x) => x.trim()).where((x) => x.isNotEmpty).toList();
    out.add(VocabEntry(m[1]!.trim(), wrong));
  }
  return (out, extra);
}

/// 写回词库文件：说明 + 一行一个词（+ 其他原样留着的正文）。
String vocabMd(List<VocabEntry> entries, [List<String> extra = const []]) => [
  defaultVocab.trimRight(),
  '',
  for (final e in entries)
    if (e.word.trim().isNotEmpty) e.wrong.isEmpty ? '- ${e.word.trim()}' : '- ${e.word.trim()}（常被听成 ${e.wrong.join('、')}）',
  if (extra.isNotEmpty) ...['', ...extra],
  '',
].join('\n');

/// 把听错的词换成对的（本地听写模型不能预设专有词，只能出字后替换）。长的错词先换，免得被短的拆开。
String fixWords(String text, List<VocabEntry> entries) {
  final pairs = [
    for (final e in entries)
      for (final w in e.wrong)
        if (w.isNotEmpty && w != e.word) (w, e.word),
  ]..sort((a, b) => b.$1.length.compareTo(a.$1.length));
  var t = text;
  for (final (w, right) in pairs) {
    t = t.replaceAll(w, right);
  }
  return t;
}
