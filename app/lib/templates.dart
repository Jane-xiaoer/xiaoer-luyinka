/// 写作风格文件里真正的内容：去掉说明行（「>」开头）和总标题；最多 [max] 字。
String cleanStyle(String raw, {int max = 6000}) {
  final t = raw
      .split('\n')
      .where((l) => !l.trimLeft().startsWith('>') && l.trim() != '# 我的写作风格')
      .join('\n')
      .replaceAll(RegExp(r'<!--[\s\S]*?-->'), '')
      .trim();
  return t.length > max ? t.substring(0, max) : t;
}
