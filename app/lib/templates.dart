''');
  for (final e in table.entries) {
    b.writeln('\n## ${e.key}\n');
    for (final (name, ask) in e.value) {
      b.writeln('- $name：$ask');
    }
  }
  return b.toString();
}

/// 读 模板/一键按钮.md：认不出一个按钮就返回 null（用默认表）。类别名写文件夹名（会议纪要）也认。
Map<String, List<(String, String)>>? parseQuickActions(String md) {
  final out = <String, List<(String, String)>>{};
  String? cat;
  for (final raw in md.split('\n')) {
    final l = raw.trim();
    final h = RegExp(r'^##\s+(.+)$').firstMatch(l);
    if (h != null) {
      final name = h[1]!.trim();
      cat = catKey(cats.firstWhere((c) => c.folder == name, orElse: () => Cat(name, '', '')).key);
      continue;
    }
    if (cat == null) continue;
    final m = RegExp(r'^[-*]\s+([^：:]+?)\s*[：:]\s*(.+)$').firstMatch(l);
    if (m != null) (out[cat] ??= []).add((m[1]!, m[2]!.trim()));
  }
  return out.isEmpty ? null : out;
}

