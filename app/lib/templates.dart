/// 提示词里的「常用词」一节（前面带空行）；没内容就是空串。
String vocabBlock(String vocab) {
  final v = vocab.trim();
  if (v.isEmpty) return '';
  return '\n\n下面是我常提到的人名 / 品牌 / 专有名词，转写里读音相近的错字按这里改（括号里写了常被转错成什么的，照着改回来）：\n$v';
}

