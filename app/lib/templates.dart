> - 王总（常被听成 王宗）
> 也可以在现场会议右上角「词库」里改。以「>」开头的说明行小耳不看。下面留空 = 没有常用词。
''';

/// 常用词文件里真正的内容：去掉说明行（「>」开头）、总标题和空行；最多 [max] 字。
String cleanVocab(String raw, {int max = 3000}) {
  final t = raw
      .replaceAll(RegExp(r'<!--[\s\S]*?-->'), '')
      .split('\n')
      .map((l) => l.trimRight())
      .where((l) => l.trim().isNotEmpty && !l.trimLeft().startsWith('>') && !RegExp(r'^#\s').hasMatch(l.trimLeft()))
      .join('\n')
      .trim();
  return t.length > max ? t.substring(0, max) : t;
}

